test('allowedAuthor: open until a complete set is known, then the set only', async (t) => {
  const lc = await load()
  const own = 'a1'.repeat(32)
  const friend = 'b2'.repeat(32)
  const stranger = 'c3'.repeat(32)
  t.teardown(() => lc.setAllowedAuthors(null))
  lc.setAllowedAuthors(null)
  t.ok(lc.allowedAuthor(stranger), 'no set yet: allowed')
  lc.setAllowedAuthors(new Set([own, friend.toUpperCase()]))
  t.ok(lc.allowedAuthor(own), 'own (passed in the set)')
  t.ok(lc.allowedAuthor(friend), 'case does not matter')
  t.absent(lc.allowedAuthor(stranger), 'outside the set')
  t.absent(lc.allowedAuthor(null))
  lc.setAllowedAuthors('nope')
  lc.setAllowedAuthors(undefined)
  t.absent(lc.allowedAuthor(stranger), 'a non-iterable changes nothing')
  lc.setAllowedAuthors(null)
  t.ok(lc.allowedAuthor(stranger), 'null forgets the set')

  lc.keepOnlyAuthors(new Set([own]))
  t.ok(lc.allowedAuthor(own))
  t.absent(lc.allowedAuthor(friend), 'keepOnlyAuthors records the set')
  lc.keepOnlyAuthors(undefined)
  t.absent(lc.allowedAuthor(friend), 'a missing set records nothing')
  lc.keepOnlyAuthors(new Set([own, friend]))
  lc.dropAuthors([friend])
  t.absent(lc.allowedAuthor(friend), 'a dropped author leaves the set')
  t.ok(lc.allowedAuthor(own))
  lc.wipeLocalCaches()
  t.ok(lc.allowedAuthor(stranger), 'a wipe forgets the set')
})

test('a dropped author stays denied until a wipe, whatever the allowed set says', async (t) => {
  const lc = await load()
  const friend = 'b2'.repeat(32)
  const other = 'd4'.repeat(32)
  t.teardown(() => lc.wipeLocalCaches())
  lc.wipeLocalCaches()
  lc.dropAuthors([friend.toUpperCase()])
  t.absent(lc.allowedAuthor(friend), 'denied even with no allowed set')
  t.ok(lc.allowedAuthor(other))
  lc.keepOnlyAuthors(new Set([friend, other]))
  t.absent(lc.allowedAuthor(friend), 'a later set that still follows them does not allow them again')
  lc.setAllowedAuthors(null)
  t.absent(lc.allowedAuthor(friend), 'nor does forgetting the set')
  lc.wipeLocalCaches()
  t.ok(lc.allowedAuthor(friend), 'a wipe clears the denial')
})

test('peekKeepAllowed: only a known stranger once the blocks are known, reset by a wipe', async (t) => {
  const lc = await load()
  const me = 'a1'.repeat(32)
  const friend = 'b2'.repeat(32)
  const stranger = 'c3'.repeat(32)
  const blocked = 'd4'.repeat(32)
  t.teardown(() => lc.wipeLocalCaches())
  lc.wipeLocalCaches()
  lc.setAllowedAuthors([me, friend])
  t.absent(lc.peekKeepAllowed(stranger), 'blocks unknown: nothing of a stranger')
  lc.noteBlocksKnown(lc.wipeEpoch())
  lc.setAllowedAuthors(null)
  t.absent(lc.peekKeepAllowed(stranger), 'allowed set unknown: nothing')
  lc.setAllowedAuthors([me, friend])
  t.ok(lc.peekKeepAllowed(stranger), 'a stranger, blocks known')
  t.ok(lc.peekKeepAllowed(stranger.toUpperCase()), 'the key is lowercased')
  t.absent(lc.peekKeepAllowed(friend), 'a followed author belongs to the main kinds')
  t.absent(lc.peekKeepAllowed(me), 'nor the own key')
  t.absent(lc.peekKeepAllowed(null), 'not a string')
  t.absent(lc.peekKeepAllowed(42))
  lc.dropAuthors([blocked])
  t.absent(lc.peekKeepAllowed(blocked), 'a denied author never')
  t.ok(lc.peekKeepAllowed(stranger), 'others still allowed')
  lc.wipeLocalCaches()
  lc.setAllowedAuthors([me, friend])
  t.absent(lc.peekKeepAllowed(stranger), 'a wipe forgets that the blocks were known')
})

test('blocksProvider notes the blocks known only after a whole list read', (t) => {
  const src = read('blocksProvider.js')
  const reload = src.slice(src.indexOf('const reload = useCallback'), src.indexOf('}, [commit])', src.indexOf('const reload = useCallback')))
  const commitAt = reload.indexOf('commit(blockedSetOf(answer))')
  const noteAt = reload.indexOf('noteBlocksKnown(wiped)')
  t.ok(commitAt !== -1 && noteAt > commitAt, 'after the denials of the list are committed')
  t.ok(reload.includes('if (answer && Array.isArray(answer.keys)) noteBlocksKnown(wiped)'), 'a malformed answer is not trusted')
  const wipedAt = reload.indexOf('const wiped = wipeEpoch()')
  const requestAt = reload.indexOf("requestRef.current('block.list', {})")
  t.ok(wipedAt !== -1 && wipedAt < requestAt, 'the wipe epoch is read before the request')
  const staleAt = reload.indexOf('if (wipeEpoch() !== wiped) return reload(alive)')
  t.ok(staleAt > requestAt && staleAt < commitAt, 'a stale answer commits nothing and the list is read again')
  const setBlock = src.slice(src.indexOf('const setBlock = useCallback'))
  t.absent(setBlock.slice(0, setBlock.indexOf('}, [')).includes('noteBlocksKnown'), 'a single block.set is not the list')
  t.is(src.split('noteBlocksKnown(').length - 1, 1, 'called in one place')
})

test('a block.list answer that started before a wipe does not mark the blocks known', async (t) => {
  const lc = await load()
  const stranger = 'c3'.repeat(32)
  t.teardown(() => lc.wipeLocalCaches())
  lc.wipeLocalCaches()
  const since = lc.wipeEpoch()
  lc.wipeLocalCaches()
  lc.setAllowedAuthors(['a1'.repeat(32)])
  lc.noteBlocksKnown(since)
  t.absent(lc.peekKeepAllowed(stranger), 'stale: the new identity still waits for its own list')
  lc.noteBlocksKnown()
  t.absent(lc.peekKeepAllowed(stranger), 'no token: nothing marked')
  lc.noteBlocksKnown(lc.wipeEpoch())
  t.ok(lc.peekKeepAllowed(stranger), 'a list read since the wipe does')
  const before = lc.wipeEpoch()
  lc.dropAuthors(['d4'.repeat(32)])
  lc.keepOnlyAuthors(new Set(['a1'.repeat(32)]))
  lc.bumpCacheGeneration()
  t.is(lc.wipeEpoch(), before, 'only a wipe changes the token')
})
