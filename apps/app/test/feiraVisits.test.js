'use strict'

const test = require('brittle')
const load = () => import('../src/feiraVisits.js')
const author = 'ab'.repeat(32)
const row = (seq, at, extra = {}) => ({ author, seq, at: new Date(at).toISOString(), ...extra })

test('visitKey names one city of one state', async (t) => {
  const { visitKey } = await load()
  t.is(visitKey({ uf: 'SP', cityKey: 'sao-paulo', kind: 'todos' }), 'SP/sao-paulo')
  t.is(visitKey(null), null)
  t.is(visitKey({ uf: 'SP' }), null)
  t.is(visitKey({ uf: '', cityKey: 'x' }), null)
})

test('a first visit marks nothing, later rows are marked, older and own ones are not', async (t) => {
  const { newRefs } = await load()
  const rows = [row(1, 300), row(2, 200), row(3, 100), row(4, 250, { author: 'cd'.repeat(32) })]
  t.is(newRefs(rows, null, { now: 1000 }).size, 0, 'no stored time: nothing is new')
  t.alike([...newRefs(rows, 200, { now: 1000 })].sort(), [author + ':1', 'cd'.repeat(32) + ':4'].sort(), 'only after the stored time, not at it')
  t.is(newRefs(rows, 200, { now: 1000, isOwn: (r) => r.author === 'cd'.repeat(32) }).size, 1, 'own rows are left out')
  t.is(newRefs([row(5, 2000)], 200, { now: 1000 }).size, 0, 'a future date does not count')
  t.is(newRefs([{ ...row(6, 300), at: 'invalid' }, null, { author, seq: 7 }], 200, { now: 1000 }).size, 0, 'unreadable rows are ignored')
  t.is(newRefs('x', 200, { now: 1000 }).size, 0)
})

test('splitNew keeps the order and puts the new rows first', async (t) => {
  const { splitNew } = await load()
  const rows = [row(1, 1), row(2, 2), row(3, 3)]
  const { fresh, older } = splitNew(rows, new Set([author + ':2', author + ':3']))
  t.alike(fresh.map((r) => r.seq), [2, 3])
  t.alike(older.map((r) => r.seq), [1])
})

test('recordVisit moves the stored time forward only, per city', async (t) => {
  const { recordVisit } = await load()
  let r = recordVisit({}, 'SP/a', 100)
  t.is(r.previous, null)
  t.alike(r.visits, { 'SP/a': 100 })
  r = recordVisit(r.visits, 'SP/b', 200)
  t.is(r.previous, null, 'another city has its own time')
  t.alike(r.visits, { 'SP/a': 100, 'SP/b': 200 })
  r = recordVisit(r.visits, 'SP/a', 50)
  t.is(r.previous, 100)
  t.is(r.visits['SP/a'], 100, 'a clock that went back does not move it')
  r = recordVisit(r.visits, 'SP/a', 300)
  t.is(r.previous, 100)
  t.is(r.visits['SP/a'], 300)
  t.alike(recordVisit(r.visits, 'SP/a', NaN).visits, r.visits, 'an unreadable time changes nothing')
  t.alike(recordVisit(r.visits, '', 400).visits, r.visits, 'no key, no record')
})

test('cleanVisits drops bad entries and keeps the most recent twenty', async (t) => {
  const { cleanVisits, MAX_VISITS } = await load()
  t.alike(cleanVisits(null), {})
  t.alike(cleanVisits([1, 2]), {})
  t.alike(cleanVisits({ a: 1, b: -1, c: 'x', d: 1.5, '': 4 }), { a: 1 })
  const many = Object.fromEntries(Array.from({ length: MAX_VISITS + 5 }, (_, i) => ['k' + i, i]))
  const kept = cleanVisits(many)
  t.is(Object.keys(kept).length, MAX_VISITS)
  t.absent('k0' in kept, 'the oldest go first')
  t.ok('k' + (MAX_VISITS + 4) in kept)
})

test('visitStep reads once, records once and only while the list is unfiltered and shown', async (t) => {
  const { visitStep } = await load()
  let step = visitStep(null, { id: 'a', shown: false })
  t.alike([step.read, step.record], [false, false], 'a list that is not shown records nothing')
  step = visitStep(step.session, { id: 'a', shown: true })
  t.alike([step.read, step.record], [true, true], 'shown: read the old time and record this one')
  step = visitStep(step.session, { id: 'a', shown: true })
  t.alike([step.read, step.record], [false, false], 'a refresh in the same visit does nothing')
  step = visitStep(step.session, { id: 'b', shown: true })
  t.alike([step.read, step.record], [true, true], 'another city is its own visit')
  step = visitStep(null, { id: 'a', shown: true, narrowed: true })
  t.alike([step.read, step.record], [true, false], 'a filtered list reads but does not use up what is new')
  step = visitStep(step.session, { id: 'a', shown: true, narrowed: true })
  t.alike([step.read, step.record], [false, false])
  step = visitStep(step.session, { id: 'a', shown: true, narrowed: false })
  t.alike([step.read, step.record], [false, true], 'the filter cleared: now it is recorded, the old time is kept')
  step = visitStep(step.session, { id: 'a', shown: true })
  t.alike([step.read, step.record], [false, false])
  t.alike([visitStep(null, { id: null, shown: true }).read, visitStep(null, {}).record], [false, false])
  step = visitStep(null, { id: 'a', shown: true })
  step = visitStep(step.session, { id: null, shown: true })
  t.is(step.session, null, 'leaving the screen ends the visit')
  step = visitStep(step.session, { id: 'a', shown: true })
  t.alike([step.read, step.record], [true, true], 'coming back is a new visit')
  step = visitStep(step.session, { id: 'a', shown: false })
  step = visitStep(step.session, { id: 'a', shown: true })
  t.alike([step.read, step.record], [false, false], 'a reload inside a visit is not a new one')
})
