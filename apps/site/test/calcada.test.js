'use strict'

const test = require('brittle')
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { render } = require('../scripts/render-calcada.js')

const SITE = path.join(__dirname, '..')
const PUBLIC = path.join(SITE, 'public')
const read = (...p) => fs.readFileSync(path.join(PUBLIC, ...p), 'utf8')
const html = read('index.html')
const css = read('styles.css')
const SCENE = path.join(SITE, '..', 'app', 'src', 'ui', 'splashScene.js')

const TOUCHED = [
  path.join(PUBLIC, 'index.html'),
  path.join(PUBLIC, 'styles.css'),
  path.join(PUBLIC, 'assets', 'varanda-cadeira.svg'),
  path.join(PUBLIC, 'assets', 'calcada-motivos.svg'),
  path.join(SITE, 'scripts', 'render-calcada.js'),
  __filename
]

test('the committed assets equal the generator output', async (t) => {
  const out = await render()
  for (const f of ['varanda-cadeira.svg', 'calcada-motivos.svg']) {
    t.is(read('assets', f), out[f], f)
    t.ok(out[f].startsWith('<!-- generated by apps/site/scripts/render-calcada.js -->\n'), f + ' names its generator')
    t.ok(/xmlns="http:\/\/www\.w3\.org\/2000\/svg"/.test(out[f]) && /viewBox="/.test(out[f]), f + ' has xmlns and viewBox')
    t.absent(/<script|<use|href|<text|data:|<image|@import/i.test(out[f]), f + ' has nothing external or active')
  }
})

test('the strip is one period of the near tiles', async (t) => {
  const m = await import(pathToFileURL(SCENE).href)
  const period = 96 * m.NEAR_SEQUENCE.length
  t.ok(read('assets', 'calcada-motivos.svg').includes('viewBox="0 0 ' + period + ' 96"'))
})

test('index.html uses the assets and the pedras layer', (t) => {
  t.ok(html.includes('assets/varanda-cadeira.svg'))
  t.ok(html.includes('assets/cadeira.svg') || fs.existsSync(path.join(PUBLIC, 'assets', 'cadeira.svg')))
  t.ok(/<div class="pedras" aria-hidden="true"><\/div>/.test(html))
  t.ok(html.indexOf('onda--perto') < html.indexOf('class="pedras"'), 'pedras is below the near wave')
  t.ok(css.includes('assets/calcada-motivos.svg'))
})

test('the hero image is the composed varanda with its alt', (t) => {
  const img = html.match(/<img class="heroi__cadeira"[^>]*>/)[0]
  t.ok(img.includes('src="assets/varanda-cadeira.svg"'))
  t.ok(img.includes('alt="O símbolo da Varanda, uma cadeira de praia, numa varanda."'))
  t.ok(img.includes('width="311"') && img.includes('height="208"'))
})

test('the hero asset carries the araucária beside the varanda', async (t) => {
  const out = await render()
  const svg = out['varanda-cadeira.svg']
  const [x, y, w, h] = /viewBox="([^"]*)"/.exec(svg)[1].split(' ').map(Number)
  t.alike(out.varandaSize, [w, h], 'the img size is the viewBox size')
  const img = html.match(/<img class="heroi__cadeira"[^>]*>/)[0]
  t.ok(img.includes('width="' + w + '"') && img.includes('height="' + h + '"'), 'img width and height match the art')
  t.ok(x < 0, 'the tree stands left of the varanda')
  t.is(x + w, 232, 'the art ends at the varanda roof, with no empty pad on the right')
  t.is(y + h, 174, 'the bottom of the art is still the varanda floor')
  t.ok(svg.includes('fill="#1a5e45"') && svg.includes('fill="#9a6b52"'), 'the tree is drawn')
  t.ok(svg.indexOf('fill="#1a5e45"') < svg.indexOf('fill="#f3ede2"'), 'before the varanda')
})

test('the CSS slide period matches stripLoops(1).near', async (t) => {
  const m = await import(pathToFileURL(SCENE).href)
  const { distance, ms } = m.stripLoops(1).near
  const rule = css.match(/\.pedras \{[^}]*\}/)[0]
  t.ok(rule.includes('background-size: ' + distance + 'px 96px'))
  t.ok(rule.includes('animation: deslizar-pedras ' + ms / 1000 + 's linear infinite'))
  t.ok(css.includes('@keyframes deslizar-pedras { to { background-position-x: -' + distance + 'px; } }'))
})

test('pedras stops with reduced motion and with the pause toggle', (t) => {
  const block = css.match(/@media \(prefers-reduced-motion: reduce\) \{[^@]*?\n\}/)[0]
  t.ok(/\.pedras[^}]*animation: none/.test(block))
  t.ok(/\.pausar:checked ~ \.calcadao \.pedras\s*\{\s*animation-play-state: paused/.test(css))
})

test('no em dash in the touched files', (t) => {
  for (const f of TOUCHED) t.absent(fs.readFileSync(f, 'utf8').includes(String.fromCharCode(0x2014)), path.basename(f))
})
