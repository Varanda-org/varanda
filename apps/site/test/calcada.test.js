test('the people stop with reduced motion and with the pause toggle', (t) => {
  const block = css.match(/@media \(prefers-reduced-motion: reduce\) \{[^@]*?\n\}/)[0]
  t.ok(/\.gente, \.gente \* \{ animation: none/.test(block))
  const spec = (sel) => [
    (sel.match(/#[\w-]+/g) || []).length,
    (sel.match(/\.[\w-]+|:[\w-]+|\[[^\]]*\]/g) || []).length,
    (sel.match(/(^|[\s>+~])[a-z][\w-]*/gi) || []).length
  ]
  const ge = (a, b) => a[0] !== b[0] ? a[0] > b[0] : a[1] !== b[1] ? a[1] > b[1] : a[2] >= b[2]
  const region = css.slice(css.indexOf('/* gente:inicio */'), css.indexOf('/* gente:fim */'))
  const reduced = block.match(/[^{}]+\{\s*animation: none[^}]*\}/g).flatMap((r) => r.split('{')[0].split(',')).map((x) => x.trim())
  t.ok(css.indexOf(block) > css.indexOf('/* gente:fim */'), 'the reduced block comes after the generated rules')
  let animated = 0
  for (const m of region.matchAll(/([^{}@]+)\{([^}]*)\}/g)) {
    if (!/(^|[\s;])animation:/.test(m[2])) continue
    for (const sel of m[1].split(',').map((x) => x.trim())) {
      animated++
      const tail = / i$/.test(sel)
      t.ok(reduced.some((r) => / i$/.test(r) === tail && ge(spec(r), spec(sel))), 'reduced motion out-ranks ' + sel)
    }
  }
  t.ok(animated > 10, 'found the animated selectors')
  t.ok(/\.pausar:checked ~ \.calcadao \.gente \*\s*\{\s*animation-play-state: paused/.test(css))
})

