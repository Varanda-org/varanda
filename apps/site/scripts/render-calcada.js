'use strict'

// Renders the landing page's calçada art (the varanda with the beach chair and
// its araucária, and one period of the near petit-pavê strip) from the splash scene module of the
// app, so the landing page and the app splash cannot drift apart.
//
// Usage: node apps/site/scripts/render-calcada.js [--write|--check]
//   --write  write the two SVGs into apps/site/public/assets
//   --check  compare them with the files on disk; writes nothing, exits 1 on drift
//
// The scene module is ESM and this repo's site tooling is CommonJS, so it is
// loaded with a dynamic import() by absolute path.

const fs = require('fs')
const path = require('path')
const { pathToFileURL } = require('url')

const ROOT = path.resolve(__dirname, '..', '..', '..')
const SCENE = path.join(ROOT, 'apps', 'app', 'src', 'ui', 'splashScene.js')
const ASSETS = path.join(ROOT, 'apps', 'site', 'public', 'assets')
const FILES = ['varanda-cadeira.svg', 'calcada-motivos.svg']
const NOTE = '<!-- generated by apps/site/scripts/render-calcada.js -->\n'

function num (n) {
  return String(Math.round(n * 1000) / 1000)
}

function shapeSvg (s, pal) {
  const a = ['d="' + s.d + '"']
  if (s.fill) {
    a.push('fill="' + (pal[s.fill] || s.fill) + '"')
    if (s.fillOpacity !== undefined) a.push('fill-opacity="' + s.fillOpacity + '"')
  } else {
    a.push('fill="none"')
  }
  if (s.stroke) {
    a.push('stroke="' + pal[s.stroke] + '"', 'stroke-width="' + s.width + '"')
    if (s.cap) a.push('stroke-linecap="' + s.cap + '"')
    if (s.join) a.push('stroke-linejoin="' + s.join + '"')
  }
  if (s.opacity !== undefined) a.push('opacity="' + s.opacity + '"')
  return '<path ' + a.join(' ') + '/>'
}

async function render () {
  const m = await import(pathToFileURL(SCENE).href)
  const pal = m.scenePalette('light')

  // the chair keeps the splash's geometry relative to the varanda, at k = 1
  const lay = m.sceneLayout({ width: 390, height: 844 })
  const scale = lay.chair.size / 256
  const cx = lay.chair.x - lay.varanda.x
  const cy = lay.chair.y - lay.varanda.y
  const art = m.varandaArt()
  // The araucária stands where the splash puts it at k = 1, drawn first so
  // the varanda covers its right side. The viewBox hugs the tree and the
  // varanda (a symmetric pad would shrink the varanda by a third in the
  // hero column), and its bottom is still the floor line the CSS aligns
  // with the sand.
  const tree = m.treeArt()
  const tx = lay.tree.x - lay.varanda.x
  const ty = lay.tree.y - lay.varanda.y
  const pad = Math.max(0, -tx)
  const vbW = art.width + pad
  const vbH = art.height - Math.min(0, ty)
  const treeScale = lay.tree.h / tree.height
  const varanda = [
    NOTE + '<svg xmlns="http://www.w3.org/2000/svg" viewBox="' + num(-pad) + ' ' + num(Math.min(0, ty)) + ' ' + num(vbW) + ' ' + num(vbH) + '">',
    '<g transform="translate(' + num(tx) + ' ' + num(ty) + ') scale(' + num(treeScale) + ')">',
    ...tree.shapes.map((s) => shapeSvg(s, pal)),
    '</g>',
    ...art.shapes.map((s) => shapeSvg(s, pal)),
    '<g transform="translate(' + num(cx) + ' ' + num(cy) + ') scale(' + num(scale) + ')">',
    ...m.CHAIR_PATHS.map((s) => shapeSvg(s, pal)),
    '</g>',
    '</svg>'
  ].join('\n') + '\n'

  const tiles = m.nearTiles()
  const period = tiles.reduce((n, t) => n + t.width, 0)
  const h = tiles[0].height
  const strip = [
    NOTE + '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + period + ' ' + h + '">',
    '<clipPath id="periodo"><rect width="' + period + '" height="' + h + '"/></clipPath>',
    '<g clip-path="url(#periodo)">',
    '<rect width="' + period + '" height="' + h + '" fill="' + pal.pedra + '"/>'
  ]
  let x = 0
  for (const t of tiles) {
    strip.push('<g transform="translate(' + x + ' 0)">', ...t.shapes.map((s) => shapeSvg(s, pal)), '</g>')
    x += t.width
  }
  strip.push('</g>', '</svg>')

  return {
    'varanda-cadeira.svg': varanda,
    'calcada-motivos.svg': strip.join('\n') + '\n',
    period,
    h,
    varandaSize: [vbW, vbH]
  }
}

async function main () {
  const out = await render()
  const check = process.argv.includes('--check')
  if (!check && !process.argv.includes('--write')) {
    console.error('usage: node apps/site/scripts/render-calcada.js [--write|--check]')
    process.exit(2)
  }
  let drift = false
  for (const f of FILES) {
    const file = path.join(ASSETS, f)
    if (check) {
      let cur = null
      try { cur = fs.readFileSync(file, 'utf8') } catch {}
      if (cur !== out[f]) {
        console.error('drift: ' + f)
        drift = true
      }
    } else {
      fs.writeFileSync(file, out[f])
    }
  }
  if (drift) process.exit(1)
}

module.exports = { render }

if (require.main === module) {
  main().catch((err) => {
    console.error(err)
    process.exit(1)
  })
}
