'use strict'

// Renders the landing page's calçada art (the varanda with the beach chair and
// its araucária, one period of the near petit-pavê strip, and the people on
// the calçadão) from the splash scene and street modules of the app, so the
// landing page and the app splash cannot drift apart.
//
// Usage: node apps/site/scripts/render-calcada.js [--write|--check]
//   --write  write the three SVGs and the two marked regions (index.html, styles.css)
//   --check  compare them with the files on disk; writes nothing, exits 1 on drift
//
// The modules are ESM and this repo's site tooling is CommonJS, so they are
// loaded with a dynamic import() by absolute path.

const fs = require('fs')
const path = require('path')
const { pathToFileURL } = require('url')

const ROOT = path.resolve(__dirname, '..', '..', '..')
const SCENE = path.join(ROOT, 'apps', 'app', 'src', 'ui', 'splashScene.js')
const STREET = path.join(ROOT, 'apps', 'app', 'src', 'ui', 'splashStreet.js')
const PUBLIC = path.join(ROOT, 'apps', 'site', 'public')
const ASSETS = path.join(PUBLIC, 'assets')
const FILES = ['varanda-cadeira.svg', 'calcada-motivos.svg', 'calcada-gente.svg']
const REGIONS = [
  { key: 'html', file: path.join(PUBLIC, 'index.html'), open: '<!-- gente:inicio -->', close: '<!-- gente:fim -->' },
  { key: 'css', file: path.join(PUBLIC, 'styles.css'), open: '/* gente:inicio */', close: '/* gente:fim */' }
]

// The pause pill covers the lower right of the stones (right 16px, about
// 210px wide), so the standing groups are anchored from the left and the
// chat is hidden where it would reach under the pill.
const PILL_RESERVE = 226
const KIDS_LEFT = 12
const RODA_LEFT = 84
const NARROW = 399
const DESKTOP = 900
const DESKTOP_SCALE = 1.25
const SHEET = 'assets/calcada-gente.svg'
const NOTE = '<!-- generated by apps/site/scripts/render-calcada.js -->\n'

function num (n) {
  return String(Math.round(n * 1000) / 1000)
}

function shapeSvg (s, pal) {
  const a = ['d="' + s.d + '"']
  if (s.fill) {
    a.push('fill="' + (pal[s.fill] || s.fill) + '"')
    if (s.fillOpacity !== undefined) a.push('fill-opacity="' + s.fillOpacity + '"')
  } else {
    a.push('fill="none"')
  }
  if (s.stroke) {
    a.push('stroke="' + pal[s.stroke] + '"', 'stroke-width="' + s.width + '"')
    if (s.cap) a.push('stroke-linecap="' + s.cap + '"')
    if (s.join) a.push('stroke-linejoin="' + s.join + '"')
  }
  if (s.opacity !== undefined) a.push('opacity="' + s.opacity + '"')
  return '<path ' + a.join(' ') + '/>'
}

function pct (p) {
  return num(p * 100) + '%'
}

function px (n) {
  return n === 0 ? '0' : num(n) + 'px'
}

// Everything the people need: the sprite sheet, the markup and the CSS.
// Positions, sizes and timings all come from the street module.
function gente (st, pal) {
  const S = st.STREET
  const sprites = []
  const rowIndex = (figure, tint) => {
    let i = sprites.findIndex((r) => r.figure === figure && r.tint === tint)
    if (i < 0) {
      sprites.push({ figure, tint, art: st.figureArt(figure, tint) })
      i = sprites.length - 1
    }
    return i
  }
  const rowOf = (name) => S.rows.find((r) => r.name === name)
  const lanes = Object.entries(S.lanes).map(([name, lane]) => ({
    name,
    lane,
    row: rowOf(lane.row),
    movers: lane.movers.map((mover) => ({ mover, ri: rowIndex(mover.figure, mover.tint) }))
  }))
  const standingRow = rowOf('standing')
  const standingFig = S.standing.map((s) => ({ s, ri: rowIndex(s.figure, s.tint) }))
  const cellW = Math.max(...sprites.map((r) => r.art.width))
  const cellH = Math.max(...sprites.map((r) => r.art.height))
  const sheetW = cellW * 2
  const sheetH = cellH * sprites.length

  const sheet = [
    NOTE + '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + sheetW + ' ' + sheetH + '">'
  ]
  sprites.forEach((r, i) => {
    ;[r.art.a, r.art.b].forEach((pose, col) => {
      sheet.push(
        '<g transform="translate(' + col * cellW + ' ' + i * cellH + ')">',
        ...r.art.body.map((x) => shapeSvg(x, pal)),
        ...pose.map((x) => shapeSvg(x, pal)),
        '</g>'
      )
    })
  })
  sheet.push('</svg>')

  // One CSS class per sprite row and size, so each figure is a box showing
  // its own cell; a figure with two poses steps between its cells.
  const classes = []
  const classFor = (ri, scale) => {
    let c = classes.find((x) => x.ri === ri && x.scale === scale)
    if (!c) {
      c = { ri, scale, n: classes.length }
      classes.push(c)
    }
    return c
  }

  const items = []
  const mIndex = { n: 0 }
  const place = { html: [], css: [], kf: [] }
  const moverBox = (lane, row, { mover, ri }) => {
    const art = sprites[ri].art
    const h = art.height * row.scale
    return {
      lane,
      ri,
      scale: row.scale,
      w: art.width * row.scale,
      h,
      top: row.feet - h,
      phase: st.moverPhase(lane.lane, mover),
      delayMs: st.moverDelayMs(lane.lane, mover)
    }
  }

  const { period, margin } = S.track
  const track = 'max(' + period + 'px, 100% + ' + 2 * margin + 'px)'
  const rest = (b) => {
    const t = 'translateX(calc(' + track + ' * ' + String(Math.round(b.phase * 1e6) / 1e6) + ' - ' + margin + 'px))'
    return b.lane.lane.mirrored ? 'scaleX(-1) ' + t : t
  }

  const standing = []
  for (const row of S.rows) {
    if (row.name === 'standing') {
      const first = standingFig[0].s
      standingFig.forEach(({ s, ri }, i) => {
        const art = sprites[ri].art
        const left = (s.figure === 'roda' ? RODA_LEFT : KIDS_LEFT + (s.x - first.x))
        const c = classFor(ri, 1)
        const top = standingRow.feet - art.height
        const hop = s.figure === 'crianca' ? st.kidHop(standingFig.slice(0, i + 1).filter((f) => f.s.figure === 'crianca').length - 1) : null
        const ball = s.figure === 'bola' ? st.ballArc() : null
        const name = 's' + i
        standing.push({ figure: s.figure, left, w: art.width })
        place.html.push('<div class="parado ' + s.figure + ' ' + name + '"><i class="g' + c.n + '"></i></div>')
        let rule = '.gente .' + name + ' { left: ' + px(left) + '; top: ' + px(top) + '; width: ' + px(art.width) + '; height: ' + px(art.height) + ';'
        if (hop) {
          rule += ' animation: gente-pula-' + i + ' ' + S.idle.ms + 'ms linear infinite;'
          place.kf.push('@keyframes gente-pula-' + i + ' { ' + hop.input.map((p, j) => pct(p) + ' { transform: translateY(' + px(hop.y[j]) + '); }').join(' ') + ' }')
        }
        if (ball) {
          rule += ' animation: gente-bola ' + S.idle.ms + 'ms linear infinite;'
          place.kf.push('@keyframes gente-bola { ' + ball.input.map((p, j) => pct(p) + ' { transform: translate(' + px(ball.x[j]) + ', ' + px(ball.y[j]) + '); }').join(' ') + ' }')
        }
        place.css.push(rule + ' }')
        if (s.mirrored) place.css.push('.gente .' + name + ' i { transform: scaleX(-1); }')
        if (art.a.length || art.b.length) {
          place.css.push('.gente .' + name + ' i { animation: gente-passo-' + c.n + ' ' + S.idle.ms + 'ms steps(1) infinite; }')
        }
      })
    } else {
      for (const lane of lanes.filter((l) => l.lane.row === row.name)) {
        for (const mv of lane.movers) {
          const b = moverBox(lane, row, mv)
          const c = classFor(mv.ri, row.scale)
          const name = 'm' + mIndex.n++
          items.push(b)
          place.html.push('<div class="anda ' + lane.name + ' ' + name + '"><i class="g' + c.n + '"></i></div>')
          place.css.push('.gente .' + name + ' { top: ' + px(b.top) + '; height: ' + px(b.h) + '; transform: ' + rest(b) + '; animation: gente-' + lane.name + ' ' + lane.lane.ms + 'ms linear -' + b.delayMs + 'ms infinite; }')
          place.css.push('.gente .' + name + ' i { animation: gente-passo-' + c.n + ' ' + lane.lane.strideMs + 'ms steps(1) infinite; }')
        }
      }
    }
  }

  const laneKf = lanes.map((l) => {
    const flip = l.lane.mirrored ? 'scaleX(-1) ' : ''
    return '@keyframes gente-' + l.name + ' { from { transform: ' + flip + 'translateX(-' + margin + 'px); } to { transform: ' + flip + 'translateX(calc(' + track + ' - ' + margin + 'px)); } }'
  })

  const spriteCss = []
  const stepKf = []
  for (const c of classes) {
    const art = sprites[c.ri].art
    const y = -c.ri * cellH * c.scale
    spriteCss.push('.gente .g' + c.n + ' { width: ' + px(art.width * c.scale) + '; height: ' + px(art.height * c.scale) + '; background-size: ' + px(sheetW * c.scale) + ' ' + px(sheetH * c.scale) + '; background-position: 0 ' + px(y) + '; }')
    if (art.a.length || art.b.length) {
      const pos = (col) => px(-col * cellW * c.scale) + ' ' + px(y)
      stepKf.push('@keyframes gente-passo-' + c.n + ' { 0% { background-position: ' + pos(0) + '; } 50% { background-position: ' + pos(1) + '; } 100% { background-position: ' + pos(0) + '; } }')
    }
  }

  const css = [
    '.gente { position: absolute; left: 0; bottom: 0; width: 100%; height: ' + S.band + 'px; overflow: hidden; pointer-events: none; z-index: 1; }',
    '.gente .palco { position: absolute; left: 0; bottom: 0; width: 100%; height: ' + S.band + 'px; }',
    '.gente .anda, .gente .parado { position: absolute; }',
    '.gente .anda { left: 0; width: 100%; }',
    '.gente i { display: block; background-image: url("' + SHEET + '"); background-repeat: no-repeat; }',
    ...spriteCss,
    ...place.css,
    ...laneKf,
    ...stepKf,
    ...place.kf,
    '@media (max-width: ' + NARROW + 'px) { .gente .roda { display: none; } }',
    '@media (min-width: ' + DESKTOP + 'px) { .gente { height: ' + S.band * DESKTOP_SCALE + 'px; } .gente .palco { width: ' + 100 / DESKTOP_SCALE + '%; transform: scale(' + DESKTOP_SCALE + '); transform-origin: left bottom; } }'
  ].join('\n')

  const html = [
    '<div class="gente" aria-hidden="true">',
    '  <div class="palco">',
    ...place.html.map((l) => '    ' + l),
    '  </div>',
    '</div>'
  ].map((l) => '    ' + l).join('\n')

  return { sheet: sheet.join('\n') + '\n', html, css, standing, movers: items, laneMs: lanes.map((l) => ({ name: l.name, ms: l.lane.ms, strideMs: l.lane.strideMs })) }
}

// Replaces what sits between the two markers, keeping the marker lines.
function apply (text, open, close, body) {
  const a = text.indexOf(open)
  const b = text.indexOf(close)
  if (a < 0 || b < a) throw new Error('markers missing: ' + open)
  const tail = text.lastIndexOf('\n', b) + 1
  return text.slice(0, a + open.length) + '\n' + body + '\n' + text.slice(tail)
}

async function render () {
  const m = await import(pathToFileURL(SCENE).href)
  const st = await import(pathToFileURL(STREET).href)
  const pal = m.scenePalette('light')

  // the chair keeps the splash's geometry relative to the varanda, at k = 1
  const lay = m.sceneLayout({ width: 390, height: 844 })
  const scale = lay.chair.size / 256
  const cx = lay.chair.x - lay.varanda.x
  const cy = lay.chair.y - lay.varanda.y
  const art = m.varandaArt()
  // The araucária stands where the splash puts it at k = 1, drawn first so
  // the varanda covers its right side. The viewBox hugs the tree and the
  // varanda (a symmetric pad would shrink the varanda by a third in the
  // hero column), and its bottom is still the floor line the CSS aligns
  // with the sand.
  const tree = m.treeArt()
  const tx = lay.tree.x - lay.varanda.x
  const ty = lay.tree.y - lay.varanda.y
  const pad = Math.max(0, -tx)
  const vbW = art.width + pad
  const vbH = art.height - Math.min(0, ty)
  const treeScale = lay.tree.h / tree.height
  const varanda = [
    NOTE + '<svg xmlns="http://www.w3.org/2000/svg" viewBox="' + num(-pad) + ' ' + num(Math.min(0, ty)) + ' ' + num(vbW) + ' ' + num(vbH) + '">',
    '<g transform="translate(' + num(tx) + ' ' + num(ty) + ') scale(' + num(treeScale) + ')">',
    ...tree.shapes.map((s) => shapeSvg(s, pal)),
    '</g>',
    ...art.shapes.map((s) => shapeSvg(s, pal)),
    '<g transform="translate(' + num(cx) + ' ' + num(cy) + ') scale(' + num(scale) + ')">',
    ...m.CHAIR_PATHS.map((s) => shapeSvg(s, pal)),
    '</g>',
    '</svg>'
  ].join('\n') + '\n'

  const tiles = m.nearTiles()
  const period = tiles.reduce((n, t) => n + t.width, 0)
  const h = tiles[0].height
  const strip = [
    NOTE + '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + period + ' ' + h + '">',
    '<clipPath id="periodo"><rect width="' + period + '" height="' + h + '"/></clipPath>',
    '<g clip-path="url(#periodo)">',
    '<rect width="' + period + '" height="' + h + '" fill="' + pal.pedra + '"/>'
  ]
  let x = 0
  for (const t of tiles) {
    strip.push('<g transform="translate(' + x + ' 0)">', ...t.shapes.map((s) => shapeSvg(s, pal)), '</g>')
    x += t.width
  }
  strip.push('</g>', '</svg>')

  const people = gente(st, pal)
  const regions = {}
  for (const r of REGIONS) regions[r.key] = apply(fs.readFileSync(r.file, 'utf8'), r.open, r.close, people[r.key])

  return {
    'varanda-cadeira.svg': varanda,
    'calcada-motivos.svg': strip.join('\n') + '\n',
    'calcada-gente.svg': people.sheet,
    'index.html': regions.html,
    'styles.css': regions.css,
    gente: people,
    pillReserve: PILL_RESERVE,
    period,
    h,
    varandaSize: [vbW, vbH]
  }
}

async function main () {
  const out = await render()
  const check = process.argv.includes('--check')
  if (!check && !process.argv.includes('--write')) {
    console.error('usage: node apps/site/scripts/render-calcada.js [--write|--check]')
    process.exit(2)
  }
  let drift = false
  const targets = [
    ...FILES.map((f) => [f, path.join(ASSETS, f)]),
    ...REGIONS.map((r) => [path.basename(r.file), r.file])
  ]
  for (const [f, file] of targets) {
    if (check) {
      let cur = null
      try { cur = fs.readFileSync(file, 'utf8') } catch {}
      if (cur !== out[f]) {
        console.error('drift: ' + f)
        drift = true
      }
    } else {
      fs.writeFileSync(file, out[f])
    }
  }
  if (drift) process.exit(1)
}

module.exports = { render }

if (require.main === module) {
  main().catch((err) => {
    console.error(err)
    process.exit(1)
  })
}
