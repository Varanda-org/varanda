'use strict'

// lib/group-activity.js: per writer core, the latest author-declared date
// of a validated plaintext group-post and that post's seq. The greatest
// date wins (and keeps that post's seq), an equal date keeps the greater
// seq, a new writer past the cap is refused, and a hostile argument stores
// nothing.
const test = require('brittle')
const fs = require('node:fs')
const path = require('node:path')
const { DEFAULT_MAX_WRITERS, createGroupActivity } = require('../lib/group-activity')

const writer = (c) => c.repeat(64)
const A = writer('a')
const B = writer('b')
const C = writer('c')

test('the greatest date is kept, and an older one does not lower it or its seq', (t) => {
  const act = createGroupActivity()
  t.is(act.lastAt(A), null)
  t.is(act.entry(A), null)
  t.is(act.observe(A, 0, 0), true)
  t.is(act.lastAt(A), 0)
  t.alike(act.entry(A), { at: 0, seq: 0 })
  t.is(act.observe(A, 50, 9), true)
  t.alike(act.entry(A), { at: 50, seq: 9 })
  // An older date with a greater seq is already newer: the record stays.
  t.is(act.observe(A, 10, 40), true)
  t.alike(act.entry(A), { at: 50, seq: 9 })
  t.is(act.lastAt(A), 50)
  // A later date is a different post, so its smaller seq replaces both.
  t.is(act.observe(A, 80, 1), true)
  t.alike(act.entry(A), { at: 80, seq: 1 })
  t.is(act.observe(A, 80, 1), true)
  t.alike(act.entry(A), { at: 80, seq: 1 })
  t.is(act.observe(B, 1, 4), true)
  t.alike(act.entry(A), { at: 80, seq: 1 })
  t.alike(act.entry(B), { at: 1, seq: 4 })
  t.alike(act.stats(), { writers: 2 })
  t.is(act.observe(A, Number.MAX_SAFE_INTEGER, Number.MAX_SAFE_INTEGER), true)
  t.alike(act.entry(A), { at: Number.MAX_SAFE_INTEGER, seq: Number.MAX_SAFE_INTEGER })
})

test('an equal date keeps the greater seq', (t) => {
  const act = createGroupActivity()
  t.is(act.observe(A, 20, 3), true)
  t.is(act.observe(A, 20, 3), true)
  t.alike(act.entry(A), { at: 20, seq: 3 })
  t.is(act.observe(A, 20, 2), true)
  t.alike(act.entry(A), { at: 20, seq: 3 })
  t.is(act.observe(A, 20, 8), true)
  t.alike(act.entry(A), { at: 20, seq: 8 })
  t.is(act.lastAt(A), 20)
  t.is(act.observe(A, 20, 8), true)
  t.alike(act.entry(A), { at: 20, seq: 8 })
})

test('a new writer past the cap is refused and an existing one still updates', (t) => {
  const act = createGroupActivity({ maxWriters: 2 })
  t.is(act.observe(A, 10, 1), true)
  t.is(act.observe(B, 20, 2), true)
  t.is(act.observe(C, 30, 3), false)
  t.is(act.lastAt(C), null)
  t.is(act.entry(C), null)
  t.alike(act.stats(), { writers: 2 })
  t.is(act.observe(A, 40, 4), true)
  t.alike(act.entry(A), { at: 40, seq: 4 })
  t.is(act.observe(A, 40, 9), true)
  t.alike(act.entry(A), { at: 40, seq: 9 })
  t.is(act.observe(B, 5, 99), true)
  t.alike(act.entry(B), { at: 20, seq: 2 })
  t.is(act.observe(C, 50, 1), false)
  t.alike(act.stats(), { writers: 2 })
})

test('the default cap is 4096 new writers', (t) => {
  t.is(DEFAULT_MAX_WRITERS, 4096)
  const act = createGroupActivity()
  let accepted = 0
  for (let i = 0; i < DEFAULT_MAX_WRITERS; i++) {
    if (act.observe(i.toString(16).padStart(64, '0'), 10, 1) === true) accepted++
  }
  t.is(accepted, DEFAULT_MAX_WRITERS)
  t.alike(act.stats(), { writers: DEFAULT_MAX_WRITERS })
  const extra = writer('f')
  t.is(act.observe(extra, 10, 1), false)
  t.is(act.lastAt(extra), null)
  t.is(act.entry(extra), null)
  t.alike(act.stats(), { writers: DEFAULT_MAX_WRITERS })
  const first = '0'.repeat(64)
  t.is(act.observe(first, 11, 4), true)
  t.alike(act.entry(first), { at: 11, seq: 4 })
  t.is(act.observe(extra, 12, 1), false)
})

test('removeWriter drops one writer so observe can store it again', (t) => {
  const act = createGroupActivity({ maxWriters: 1 })
  t.is(act.removeWriter(A), false)
  t.is(act.observe(A, 5, 1), true)
  t.is(act.observe(B, 6, 1), false)
  t.is(act.removeWriter(A), true)
  t.is(act.removeWriter(A), false)
  t.is(act.lastAt(A), null)
  t.is(act.entry(A), null)
  t.alike(act.stats(), { writers: 0 })
  t.is(act.observe(B, 9, 3), true)
  t.alike(act.entry(B), { at: 9, seq: 3 })
  t.is(act.lastAt(A), null)
  t.is(act.observe(A, 8, 2), false)
  t.is(act.removeWriter(B), true)
  t.is(act.observe(A, 8, 2), true)
  t.alike(act.entry(A), { at: 8, seq: 2 })
  t.alike(act.stats(), { writers: 1 })
})

test('entry returns a fresh copy', (t) => {
  const act = createGroupActivity()
  t.is(act.observe(A, 7, 2), true)
  const copy = act.entry(A)
  t.alike(copy, { at: 7, seq: 2 })
  copy.at = 0
  copy.seq = 99
  copy.extra = true
  t.alike(act.entry(A), { at: 7, seq: 2 })
  t.is(act.lastAt(A), 7)
  t.is(act.observe(A, 99, 7), true)
  t.alike(copy, { at: 0, seq: 99, extra: true })
  t.alike(act.entry(A), { at: 99, seq: 7 })
})

test('clear drops every writer and stats counts those held', (t) => {
  const one = createGroupActivity()
  const two = createGroupActivity()
  t.alike(one.stats(), { writers: 0 })
  t.is(one.observe(A, 1, 1), true)
  t.is(one.observe(B, 2, 1), true)
  t.is(one.observe(A, 3, 2), true)
  t.alike(one.stats(), { writers: 2 })
  t.is(two.lastAt(A), null)
  t.alike(two.stats(), { writers: 0 })
  const snap = one.stats()
  snap.writers = 50
  t.alike(one.stats(), { writers: 2 })
  one.clear()
  t.alike(one.stats(), { writers: 0 })
  t.is(one.lastAt(A), null)
  t.is(one.entry(A), null)
  t.is(one.entry(B), null)
  t.is(one.removeWriter(A), false)
  two.clear()
  t.alike(two.stats(), { writers: 0 })
  t.is(one.observe(A, 4, 1), true)
  t.alike(one.entry(A), { at: 4, seq: 1 })
  t.alike(one.stats(), { writers: 1 })
  t.alike(two.stats(), { writers: 0 })
})

test('a cap that is not a safe integer >= 0 falls back to the default', (t) => {
  for (const bad of [-1, 1.5, NaN, 2 ** 60, Infinity, '4096', null, true]) {
    const act = createGroupActivity({ maxWriters: bad })
    t.is(act.observe(A, 1, 1), true, String(bad))
    t.is(act.observe(B, 1, 1), true, String(bad))
    // 1.5 as a cap would refuse the third writer (2 >= 1.5).
    t.is(act.observe(C, 1, 1), true, String(bad))
  }
  t.is(createGroupActivity(null).observe(A, 1, 0), true)
  t.is(createGroupActivity(1).observe(A, 1, 0), true)
  t.is(createGroupActivity('x').observe(A, 1, 0), true)
  const boom = new Proxy({}, { get () { throw new Error('x') } })
  t.is(createGroupActivity(boom).observe(A, 1, 1), true)
  const zero = createGroupActivity({ maxWriters: 0 })
  t.is(zero.observe(A, 1, 1), false)
  t.is(zero.lastAt(A), null)
  t.alike(zero.stats(), { writers: 0 })
  zero.clear()
  t.is(zero.observe(A, 1, 1), false)
})

test('hostile arguments answer false or null and store nothing', (t) => {
  const act = createGroupActivity()
  t.is(act.observe(A, 40, 3), true)
  const same = () => {
    t.alike(act.entry(A), { at: 40, seq: 3 })
    t.alike(act.stats(), { writers: 1 })
  }
  const refuse = (who, atMs, seq) => {
    t.is(act.observe(who, atMs, seq), false)
    same()
  }
  refuse(null, 1, 1)
  refuse(undefined, 1, 1)
  refuse(1, 1, 1)
  refuse(0, 1, 1)
  refuse(2 ** 60, 1, 1)
  refuse(writer('A'), 5, 1)
  refuse(writer('a').slice(0, 63), 5, 1)
  refuse(writer('a') + 'a', 5, 1)
  refuse(writer('a').slice(0, 63) + 'A', 5, 1)
  refuse(writer('g'), 5, 1)
  refuse(A, NaN, 1)
  refuse(A, -1, 1)
  refuse(A, 2 ** 60, 1)
  refuse(A, 1.5, 1)
  refuse(A, Infinity, 1)
  refuse(A, 1, NaN)
  refuse(A, 1, -1)
  refuse(A, 1, 2 ** 60)
  refuse(A, 1, 1.5)
  refuse(A, -5, -5)
  refuse(A, '40', 1)
  refuse(A, 1, '3')
  t.is(act.observe(), false)
  same()
  t.is(act.lastAt(null), null)
  t.is(act.lastAt(1), null)
  t.is(act.lastAt(writer('A')), null)
  t.is(act.lastAt(writer('a').slice(0, 63)), null)
  t.is(act.lastAt(NaN), null)
  t.is(act.entry(null), null)
  t.is(act.entry(1), null)
  t.is(act.entry(writer('A')), null)
  t.is(act.entry(-1), null)
  t.is(act.removeWriter(null), false)
  t.is(act.removeWriter(1), false)
  t.is(act.removeWriter(writer('A')), false)
  t.is(act.removeWriter(writer('a').slice(0, 63)), false)
  t.is(act.removeWriter(2 ** 60), false)
  same()
})

