'use strict'

// The perfil rico pointers of the seeder's engagement index (profileExtra()):
// the newest live profile-about and mood seq of an author, deletion falling
// back to the previous block, purge, and no effect on the other hints. The
// answer is an open object, so keys are asserted by name only. No network.
const test = require('brittle')
const { createEngagementIndex } = require('../lib/engagement-index')
const { profileAboutRecord, moodRecord, profileRecord, topFriendsRecord, visitsRecord, gardenRecord, gardenStateRecord, validRecordCopy } = require('../lib/records')

const A = 'a'.repeat(64)
const B = 'b'.repeat(64)
const C = 'c'.repeat(64)
const at = (i) => new Date(Date.UTC(2026, 2, 1, 12, 0, i)).toISOString()

function add (ix, author, seq, record, opts = null) {
  return ix.add(author, seq, validRecordCopy(record, seq), opts)
}

test('profileExtra: null pointers for an unknown author and for one without blocks', (t) => {
  const ix = createEngagementIndex()
  t.is(ix.profileExtra(A).about, null)
  t.is(ix.profileExtra(A).mood, null)
  t.is(ix.profileExtra(undefined).about, null, 'a malformed key is total')
  add(ix, A, 1, profileRecord({ name: 'Ana', at: at(1) }))
  const got = ix.profileExtra(A)
  t.is(got.about, null)
  t.is(got.mood, null)
  t.is(ix.hints(A).profileSeq, 1, 'the profile hint is untouched')
})

test('profileExtra: the newest live block of each type wins, older or equal seqs never override', (t) => {
  const ix = createEngagementIndex()
  t.ok(add(ix, A, 1, profileAboutRecord({ about: 'um', at: at(1) })))
  t.ok(add(ix, A, 2, moodRecord({ emoji: '🙂', text: 'bem', at: at(2) })))
  t.ok(add(ix, A, 3, profileAboutRecord({ about: 'dois', at: at(3) })))
  t.ok(add(ix, A, 4, moodRecord({ emoji: '🎉', text: '', at: at(4) })))
  t.is(ix.profileExtra(A).about, 3)
  t.is(ix.profileExtra(A).mood, 4)
  t.ok(add(ix, A, 3, profileAboutRecord({ about: 'dois', at: at(3) })), 'a re-add is a no-op')
  t.is(ix.profileExtra(A).about, 3)
  t.is(ix.profileExtra(B).about, null, 'another author is unaffected')
  t.is(ix.stats().records, 4, 'each block holds one record slot, once')
})

test('profileExtra: a seq arriving out of order still leaves the highest as the pointer', (t) => {
  const ix = createEngagementIndex()
  add(ix, A, 5, profileAboutRecord({ about: 'cinco', at: at(5) }))
  add(ix, A, 2, profileAboutRecord({ about: 'dois', at: at(2) }))
  t.is(ix.profileExtra(A).about, 5)
})

test('profileExtra: deleting the newest block falls back to the previous live one, then to null', (t) => {
  const ix = createEngagementIndex()
  add(ix, A, 1, profileAboutRecord({ about: 'um', at: at(1) }))
  add(ix, A, 2, moodRecord({ emoji: '🙂', text: 'a', at: at(2) }))
  add(ix, A, 3, profileAboutRecord({ about: 'tres', at: at(3) }))
  add(ix, A, 4, moodRecord({ emoji: '🎉', text: 'b', at: at(4) }))
  t.ok(ix.removeRecord(A, 3))
  t.is(ix.profileExtra(A).about, 1, 'about falls back')
  t.is(ix.profileExtra(A).mood, 4, 'mood untouched')
  t.ok(ix.removeRecord(A, 4))
  t.is(ix.profileExtra(A).mood, 2)
  t.ok(ix.removeRecord(A, 1))
  t.ok(ix.removeRecord(A, 2))
  t.is(ix.profileExtra(A).about, null)
  t.is(ix.profileExtra(A).mood, null)
  t.is(ix.stats().records, 0, 'every slot was released')
  t.ok(add(ix, A, 3, profileAboutRecord({ about: 'tres', at: at(3) })), 'a tombstoned seq is not resurrected')
  t.is(ix.profileExtra(A).about, null)
})

test('profileExtra: a tombstone scanned before the block keeps it out (deletes first)', (t) => {
  const ix = createEngagementIndex()
  ix.removeRecord(A, 2)
  add(ix, A, 1, profileAboutRecord({ about: 'um', at: at(1) }))
  add(ix, A, 2, profileAboutRecord({ about: 'dois', at: at(2) }))
  add(ix, A, 3, moodRecord({ emoji: '🙂', text: '', at: at(3) }))
  t.is(ix.profileExtra(A).about, 1)
  t.is(ix.profileExtra(A).mood, 3)
})

test('profileExtra: profile.extra.delete tombstones every version in one append, so nothing falls back', (t) => {
  const ix = createEngagementIndex()
  add(ix, A, 1, profileAboutRecord({ about: 'um', at: at(1) }))
  add(ix, A, 2, moodRecord({ emoji: '🙂', text: 'a', at: at(2) }))
  add(ix, A, 3, profileAboutRecord({ about: 'tres', at: at(3) }))
  add(ix, A, 4, profileAboutRecord({ about: 'quatro', at: at(4) }))
  // The seeder applies the tombstones of blocks 5, 6 and 7 one by one.
  for (const seq of [1, 3, 4]) t.ok(ix.removeRecord(A, seq))
  t.is(ix.profileExtra(A).about, null, 'no older version comes back')
  t.is(ix.profileExtra(A).mood, 2, 'the other type is untouched')
  t.is(ix.stats().records, 1, 'the three slots were released')
})

test('profileExtra: removeDiary purges the pointers and frees the slots', (t) => {
  const ix = createEngagementIndex()
  add(ix, A, 1, profileAboutRecord({ about: 'um', at: at(1) }))
  add(ix, A, 2, moodRecord({ emoji: '🙂', text: 'a', at: at(2) }))
  add(ix, B, 1, profileAboutRecord({ about: 'b', at: at(1) }))
  ix.removeDiary(A)
  t.is(ix.profileExtra(A).about, null)
  t.is(ix.profileExtra(A).mood, null)
  t.is(ix.profileExtra(B).about, 1, 'another diary stays')
  t.is(ix.stats().records, 1)
  ix.clear()
  t.is(ix.profileExtra(B).about, null)
})

test('profileExtra: the answer carries the about, mood and top keys by name (later features add more)', (t) => {
  const ix = createEngagementIndex()
  const got = ix.profileExtra(A)
  t.ok('about' in got)
  t.ok('mood' in got)
  t.ok('top' in got)
  t.is(got.top, null)
  t.ok('visits' in got)
  t.is(got.visits, null)
  t.ok('garden' in got)
  t.is(got.garden, null)
})

test('profileExtra: visits is the newest live visits block (on or off), deletes fall back, slots and purge', (t) => {
  const ix = createEngagementIndex()
  t.is(ix.profileExtra(A).visits, null)
  t.ok(add(ix, A, 1, visitsRecord({ on: true, at: at(1) })))
  t.is(ix.profileExtra(A).visits, 1)
  t.ok(add(ix, A, 2, visitsRecord({ on: false, at: at(2) })))
  t.is(ix.profileExtra(A).visits, 2, 'an off block is still the pointer (the node peeks it)')
  t.ok(add(ix, A, 3, visitsRecord({ on: true, at: at(3) })))
  t.ok(add(ix, A, 3, visitsRecord({ on: true, at: at(3) })), 'a re-add is a no-op')
  t.is(ix.profileExtra(A).visits, 3)
  t.is(ix.stats().records, 3, 'each block holds one slot, once')
  t.is(ix.profileExtra(B).visits, null, 'another author is unaffected')
  t.is(ix.profileExtra(A).about, null, 'the other pointers are unaffected')
  t.ok(ix.removeRecord(A, 3))
  t.is(ix.profileExtra(A).visits, 2, 'a deleted block falls back')
  t.ok(add(ix, A, 3, visitsRecord({ on: true, at: at(3) })), 'a tombstoned seq is not resurrected')
  t.is(ix.profileExtra(A).visits, 2)
  t.ok(ix.removeRecord(A, 2))
  t.ok(ix.removeRecord(A, 1))
  t.is(ix.profileExtra(A).visits, null)
  t.is(ix.stats().records, 0, 'every slot was released')
  add(ix, B, 1, visitsRecord({ on: true, at: at(4) }))
  add(ix, B, 2, moodRecord({ emoji: '🙂', text: '', at: at(5) }))
  ix.removeDiary(B)
  t.is(ix.profileExtra(B).visits, null, 'removeDiary purges it')
  t.is(ix.stats().records, 0)
  add(ix, A, 7, visitsRecord({ on: true, at: at(6) }))
  ix.clear()
  t.is(ix.profileExtra(A).visits, null, 'clear purges it')
})

test('profileExtra: a visits record out of order or with a malformed on is handled', (t) => {
  const ix = createEngagementIndex()
  add(ix, A, 5, visitsRecord({ on: false, at: at(5) }))
  add(ix, A, 2, visitsRecord({ on: true, at: at(2) }))
  t.is(ix.profileExtra(A).visits, 5, 'the highest seq stays the pointer')
  t.absent(ix.add(A, 9, { type: 'visits', on: 'yes', at: at(9) }), 'a non-boolean on is refused')
  t.is(ix.profileExtra(A).visits, 5)
})

test('profileExtra: top is the newest live top-friends block with its keys, deletes fall back', (t) => {
  const ix = createEngagementIndex()
  t.ok(add(ix, A, 1, topFriendsRecord({ keys: [B], at: at(1) })))
  t.ok(add(ix, A, 2, moodRecord({ emoji: '🙂', text: 'a', at: at(2) })))
  t.ok(add(ix, A, 3, topFriendsRecord({ keys: [C, B], at: at(3) })))
  t.alike(ix.profileExtra(A).top, { seq: 3, keys: [C, B] }, 'latest wins, order kept')
  ix.profileExtra(A).top.keys.push('x')
  t.alike(ix.profileExtra(A).top.keys, [C, B], 'the keys are a fresh copy')
  t.is(ix.profileExtra(A).mood, 2, 'the other pointers are untouched')
  t.ok(ix.removeRecord(A, 3))
  t.alike(ix.profileExtra(A).top, { seq: 1, keys: [B] }, 'a deleted block falls back')
  t.ok(add(ix, A, 4, topFriendsRecord({ keys: [], at: at(4) })))
  t.alike(ix.profileExtra(A).top, { seq: 4, keys: [] }, 'an empty list is a list')
  t.is(ix.stats().records, 3)
  ix.removeDiary(A)
  t.is(ix.profileExtra(A).top, null)
  t.is(ix.stats().records, 0)
})

test('profileExtra: a top-friends block naming its writer or malformed takes no slot', (t) => {
  const ix = createEngagementIndex()
  add(ix, A, 1, topFriendsRecord({ keys: [B], at: at(1) }))
  t.ok(ix.add(A, 2, { type: 'top-friends', keys: [B, A], at: at(2) }), 'self: skipped, the cursor moves on')
  t.alike(ix.profileExtra(A).top, { seq: 1, keys: [B] }, 'the earlier list stays')
  t.absent(ix.add(A, 3, { type: 'top-friends', keys: [B, B], at: at(3) }), 'a duplicate key is refused')
  t.absent(ix.add(A, 3, { type: 'top-friends', keys: Array.from({ length: 9 }, (_, i) => String(i).repeat(64)), at: at(3) }), 'more than eight keys are refused')
  t.absent(ix.add(A, 3, { type: 'top-friends', keys: 'nope', at: at(3) }))
  t.is(ix.stats().records, 1)
})

test('profileExtra: a record refused at the per-author cap leaves no pointer', (t) => {
  const ix = createEngagementIndex({ perAuthorMax: 1 })
  t.ok(add(ix, A, 1, profileAboutRecord({ about: 'um', at: at(1) })))
  t.absent(add(ix, A, 2, moodRecord({ emoji: '🙂', text: 'a', at: at(2) })), 'refused: the cursor pauses')
  t.is(ix.profileExtra(A).about, 1)
  t.is(ix.profileExtra(A).mood, null)
})

test('profileExtra: garden is the newest live garden block (on or off), deletes fall back, slots and purge', (t) => {
  const ix = createEngagementIndex()
  t.is(ix.profileExtra(A).garden, null)
  t.ok(add(ix, A, 1, gardenRecord({ on: true, at: at(1) })))
  t.is(ix.profileExtra(A).garden, 1)
  t.ok(add(ix, A, 2, gardenRecord({ on: false, at: at(2) })))
  t.is(ix.profileExtra(A).garden, 2, 'an off block is still the pointer (the node peeks it)')
  t.ok(add(ix, A, 3, gardenStateRecord({ pots: [null, null, null, null, null, null], n: 1, at: at(3) })))
  t.is(ix.profileExtra(A).garden, 2, 'a garden-state block is not the flag pointer')
  t.ok(add(ix, A, 4, gardenRecord({ on: true, at: at(4) })))
  t.ok(add(ix, A, 4, gardenRecord({ on: true, at: at(4) })), 'a re-add is a no-op')
  t.is(ix.profileExtra(A).garden, 4)
  t.is(ix.stats().records, 4, 'each block holds one slot, once')
  t.is(ix.profileExtra(A).visits, null, 'the other pointers are unaffected')
  t.is(ix.profileExtra(B).garden, null, 'another author is unaffected')
  t.ok(ix.removeRecord(A, 4))
  t.is(ix.profileExtra(A).garden, 2, 'a deleted block falls back, even to an off one')
  t.ok(add(ix, A, 4, gardenRecord({ on: true, at: at(4) })), 'a tombstoned seq is not resurrected')
  t.is(ix.profileExtra(A).garden, 2)
  t.ok(ix.removeRecord(A, 2))
  t.ok(ix.removeRecord(A, 1))
  t.is(ix.profileExtra(A).garden, null)
  t.ok(ix.removeRecord(A, 3))
  t.is(ix.stats().records, 0, 'every slot was released')
  add(ix, B, 1, gardenRecord({ on: true, at: at(5) }))
  ix.removeDiary(B)
  t.is(ix.profileExtra(B).garden, null, 'removeDiary purges it')
  t.is(ix.stats().records, 0)
  add(ix, A, 7, gardenRecord({ on: true, at: at(6) }))
  ix.clear()
  t.is(ix.profileExtra(A).garden, null, 'clear purges it')
})
